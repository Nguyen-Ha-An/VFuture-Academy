import assert from 'node:assert/strict';
import {readFileSync,rmSync} from 'node:fs';
import {loadPGlite,repositoryRoot} from './lib/admin-db-harness.mjs';
import {join} from 'node:path';
const {PGlite,temporaryPrefix}=await loadPGlite(process.env.PGLITE_MODULE_PATH);
const db=new PGlite();
const owner='00000000-0000-4000-8000-000000000001';
const other='00000000-0000-4000-8000-000000000002';
const version='00000000-0000-4000-8000-000000000003';
const template='00000000-0000-4000-8000-000000000004';
const first='00000000-0000-4000-8000-000000000005';
const second='00000000-0000-4000-8000-000000000006';
let passed=0;
try{
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create schema storage;
 create table auth.users(id uuid primary key);create table public.courses(id text primary key,ownership_kind text default 'central',owner_branch_id text);
 create table public.course_versions(id uuid primary key);create table public.media_assets(id text primary key,owner_id uuid,bucket text,path text,mime text,size_bytes bigint,ownership_kind text,owner_branch_id text);
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table public.cms_content_snapshots(content_id text,dependencies jsonb);
 grant usage on schema public to anon,authenticated,service_role;`);
 await db.query('insert into auth.users values($1),($2)',[owner,other]);
 await db.exec("insert into courses(id) values('python');");
 await db.query('insert into course_versions values($1)',[version]);
 await db.exec(readFileSync(join(repositoryRoot,'supabase/migrations/20260906065957_notebook_foundation.sql'),'utf8'));
 const insert=async(id,purpose)=>db.query(`insert into notebook_artifacts(id,owner_id,course_id,course_version_id,item_id,block_id,purpose,checksum,template_asset_id,template_checksum,runtime_profile_id,runtime_profile_version,size_bytes,mime,filename,storage_path)
 values($1,$2,'python',$3,'practice',null,$4,$5,$6,$7,'python-data-v1','1',100,'application/x-ipynb+json','work.ipynb',$8)`,[id,owner,purpose==='template'?null:version,purpose,'a'.repeat(64),purpose==='template'?null:template,purpose==='template'?null:'a'.repeat(64),'pending/'+id]);
 const finalize=async(id)=>db.query('select finalize_notebook_artifact($1,$2,$3,$4,100)',[id,owner,'ready/'+id,'a'.repeat(64)]);
 await insert(template,'template');await finalize(template);await insert(first,'draft');await finalize(first);await insert(second,'draft');await finalize(second);
 await db.exec('set role service_role');
 const save=async(actor,id,revision)=>{const r=await db.query('select save_notebook_draft($1,$2,\'practice\',null,$3,$4) as result',[actor,version,id,revision]);return r.rows[0].result;};
 assert.equal((await save(owner,first,0)).revision,1);passed++;
 assert.equal((await save(owner,second,0)).conflict,true);passed++;
 assert.equal((await save(owner,second,1)).revision,2);passed++;
 await assert.rejects(()=>save(other,first,0),/NOTEBOOK_ARTIFACT_INVALID/);passed++;
 await assert.rejects(()=>db.query('update notebook_artifacts set checksum=$1 where id=$2',['b'.repeat(64),first]),/permission denied/);passed++;
 await assert.rejects(()=>db.query('delete from notebook_artifacts where id=$1',[first]),/NOTEBOOK_ARTIFACT_IMMUTABLE/);passed++;
 await finalize(first);passed++;
 await db.exec('reset role; set role authenticated');
 await assert.rejects(()=>db.query('select * from notebook_artifacts'),/permission denied/);passed++;
 await assert.rejects(()=>save(owner,first,2),/permission denied/);passed++;
 await db.exec('reset role;set role anon');
 await assert.rejects(()=>db.query('select * from notebook_drafts'),/permission denied/);passed++;
 await assert.rejects(()=>finalize(first),/permission denied/);passed++;
 await db.exec('reset role');
 const row=await db.query('select revision,artifact_id from notebook_drafts');assert.equal(row.rows.length,1);assert.equal(row.rows[0].revision,2);assert.equal(row.rows[0].artifact_id,second);passed++;
 const snapshot=async(assets)=>db.query('insert into cms_content_snapshots values($1,$2)', ['python', JSON.stringify([{kind:'notebook',assets}])]);
 await assert.rejects(()=>snapshot([]),/CMS_NOTEBOOK_DEPENDENCIES_INVALID/);passed++;
 await assert.rejects(()=>snapshot([{id:template,purpose:'template',checksum:'b'.repeat(64),sizeBytes:100}]),/CMS_NOTEBOOK_DEPENDENCIES_INVALID/);passed++;
 await assert.rejects(()=>snapshot([{id:template,purpose:'template',checksum:'a'.repeat(64),sizeBytes:999}]),/CMS_NOTEBOOK_DEPENDENCIES_INVALID/);passed++;
 await snapshot([{id:template,purpose:'template',checksum:'a'.repeat(64),sizeBytes:100}]);passed++;
 console.log(`Notebook PostgreSQL verification: ${passed} assertions passed (private access, immutable artifacts, stale revision, actor mismatch, retry).`);
}finally{await db.close();if(temporaryPrefix)rmSync(temporaryPrefix,{recursive:true,force:true});}
